}

pub fn failureRoleName(role: FailureRole) []const u8 {
    return @tagName(role);
}

pub fn currentSemanticTagForWire(operation: WireOperation) u8 {
    return @intCast(@intFromEnum(operation) + 1);
}

pub fn failureRolesForWire(operation: WireOperation) []const FailureRole {
    return switch (operation) {
        .integer_add,
        .integer_subtract,
        .integer_multiply,
        .integer_negate,
        .integer_convert,
        => &.{.arithmetic_overflow},
        .integer_divide, .integer_remainder => &.{
            .arithmetic_overflow,
            .division_by_zero,
        },
        .sum_extract => &.{.invalid_variant},
        .vector_get, .vector_set, .text_byte_at, .bytes_byte_at => &.{.invalid_index},
        .text_append_scalar, .text_copy => &.{
            .capacity_exceeded,
            .invalid_utf8,
        },
        .vector_push,
        .text_append,
        .text_append_unsigned,
        .text_append_signed,
        .text_join,
        .bytes_append,
        .bytes_append_scalar,
        .bytes_copy,
        .bytes_join,
        => &.{.capacity_exceeded},
        .constant,
        .copy,
        .compare_eq_zero,
        .integer_equal,
        .integer_not_equal,
        .integer_less_than,
        .integer_less_equal,
        .integer_greater_than,
        .integer_greater_equal,
        .integer_bit_not,
        .integer_bit_and,
        .integer_bit_or,
        .integer_bit_xor,
        .boolean_not,
        .boolean_and,
        .boolean_or,
        .select,
        .product_construct,
        .product_extract,
        .product_replace,
        .sum_construct,
        .sum_tag_is,
        .optional_none,
        .optional_some,
        .optional_is_some,
        .vector_empty,
        .vector_length,
        .vector_pop,
        .vector_truncate,
        .vector_clear,
        .text_empty,
        .text_compare,
        .bytes_empty,
        .bytes_compare,
        .text_length,
        .bytes_length,
        .enum_to_u32,
        => &.{},
    };
}
