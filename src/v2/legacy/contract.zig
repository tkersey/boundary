pub fn fixedOperandCount(operation: WireOperation) ?u16 {
    return switch (operation) {
        .product_construct, .sum_construct => null,
        .constant,
        .optional_none,
        .vector_empty,
        .text_empty,
        .bytes_empty,
        => 0,
        .copy,
        .compare_eq_zero,
        .integer_negate,
        .integer_bit_not,
        .integer_convert,
        .boolean_not,
        .product_extract,
        .sum_tag_is,
        .sum_extract,
        .optional_some,
        .optional_is_some,
        .vector_length,
        .vector_pop,
        .vector_clear,
        .text_length,
        .bytes_length,
        .enum_to_u32,
        => 1,
        .integer_add,
        .integer_subtract,
        .integer_multiply,
        .integer_divide,
        .integer_remainder,
        .integer_equal,
        .integer_not_equal,
        .integer_less_than,
        .integer_less_equal,
        .integer_greater_than,
        .integer_greater_equal,
        .integer_bit_and,
        .integer_bit_or,
        .integer_bit_xor,
        .boolean_and,
        .boolean_or,
        .product_replace,
        .vector_get,
